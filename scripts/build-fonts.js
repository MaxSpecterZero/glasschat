// Bundles variable fonts (Fontsource, OFL) into src/fonts.css as data: URLs so they
// load inside WhatsApp Web offline and without contacting any font server.
'use strict';
const fs = require('fs');
const path = require('path');

const FAMILIES = [
  ['inter', ['latin', 'latin-ext', 'cyrillic', 'greek']],
  ['plus-jakarta-sans', ['latin', 'latin-ext']],
  ['figtree', ['latin', 'latin-ext']],
  ['manrope', ['latin', 'latin-ext', 'cyrillic']],
  ['outfit', ['latin', 'latin-ext']]
];

let out = '/* Generated by scripts/build-fonts.js — fonts from Fontsource (SIL Open Font License). */\n';
for (const [pkg, subsets] of FAMILIES) {
  const dir = path.join(__dirname, '..', 'node_modules', '@fontsource-variable', pkg);
  const css = fs.readFileSync(path.join(dir, 'index.css'), 'utf8');
  const re = /\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]*)}/g;
  let m, n = 0;
  while ((m = re.exec(css))) {
    const subset = m[1].replace(pkg + '-', '').replace('-wght-normal', '');
    if (!subsets.includes(subset)) continue;
    const body = m[2].replace(/src:[^;]*;/, () => {
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(m[2])[1];
      const b64 = fs.readFileSync(path.join(dir, 'files', file)).toString('base64');
      return `src: url(data:font/woff2;base64,${b64}) format('woff2-variations');`;
    });
    out += `@font-face {${body.trim().replace(/\s+/g, ' ')}}\n`;
    n++;
  }
  console.log(pkg, n, 'faces');
}
fs.writeFileSync(path.join(__dirname, '..', 'src', 'fonts.css'), out);
console.log('fonts.css', Math.round(out.length / 1024), 'KB');
